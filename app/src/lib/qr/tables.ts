/** Bits del nivel de corrección en la información de formato. */
export const FORMAT_BITS: Record<ErrorCorrectionLevel, number> = { L: 1, M: 0, Q: 3, H: 2 };

/** Lado del símbolo en módulos (21 en la versión 1, +4 por versión). */
export function symbolSize(version: number): number {
  return version * 4 + 17;
}

/** Módulos disponibles para datos y corrección una vez descontados los patrones fijos y la información de formato y versión. */
export function rawDataModules(version: number): number {
  let modules = (16 * version + 128) * version + 64;
  if (version >= 2) {
    const alignmentCount = Math.floor(version / 7) + 2;
    modules -= (25 * alignmentCount - 10) * alignmentCount - 55;
    if (version >= 7) modules -= 36;
  }
  return modules;
}

/** Estructura de bloques de una versión y nivel: total de codewords, bloques y codewords de corrección por bloque. */
export interface BlockLayout {
  totalCodewords: number;
  blockCount: number;
  eccPerBlock: number;
  dataCodewords: number;
}

export function blockLayout(version: number, level: ErrorCorrectionLevel): BlockLayout {
  const totalCodewords = Math.floor(rawDataModules(version) / 8);
  const blockCount = at(ERROR_CORRECTION_BLOCKS[level], version);
  const eccPerBlock = at(ECC_CODEWORDS_PER_BLOCK[level], version);
  return { totalCodewords, blockCount, eccPerBlock, dataCodewords: totalCodewords - blockCount * eccPerBlock };
}

/** Coordenadas (fila y columna) de los centros de los patrones de alineación. */
export function alignmentPositions(version: number): number[] {
  if (version === 1) return [];
  const count = Math.floor(version / 7) + 2;
  const step = version === 32 ? 26 : Math.ceil((version * 4 + 4) / (count * 2 - 2)) * 2;
  const positions = [6];
  for (let position = symbolSize(version) - 7; positions.length < count; position -= step)
    positions.splice(1, 0, position);
  return positions;
}
